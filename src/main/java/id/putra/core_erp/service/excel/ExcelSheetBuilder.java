package id.putra.core_erp.service.excel;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.ZonedDateTime;
import java.util.List;

import org.apache.poi.ss.usermodel.Cell;
import org.apache.poi.ss.usermodel.CellStyle;
import org.apache.poi.ss.usermodel.PageMargin;
import org.apache.poi.ss.usermodel.Row;
import org.apache.poi.ss.usermodel.Sheet;
import org.apache.poi.ss.usermodel.Workbook;
import org.apache.poi.ss.util.CellRangeAddress;

/**
 * Renders an {@link ExcelReport} onto a worksheet using the {@link ExcelStyles} palette.
 *
 * <p>Produces a fixed document layout:
 *
 * <pre>
 *   row 0   COMPANY NAME                       merged, centred, 14pt bold navy
 *   row 1   REPORT TITLE                       merged, centred, 16pt bold
 *   row 2   Period: ... | Generated: ...       merged, centred, 10pt italic grey
 *   row 3   (spacer, 6pt tall)
 *   row 4   No. | SKU | PRODUCT NAME | ...     header, frozen, autofiltered
 *   row 5.. data rows                          zebra striped, bordered
 *   row n   TOTAL                              bold, grey fill, medium top border
 *   row n+1 (spacer, 6pt tall)
 *   row n+2 Generated by CORE ERP on ...       8pt italic grey
 * </pre>
 *
 * <p>Column widths come from {@link ExcelColumn#width()} rather than {@code autoSizeColumn}:
 * auto-sizing depends on the fonts installed in the JVM, so widths differ between a developer
 * machine and a headless server, and wide text columns blow up the sheet.
 */
public final class ExcelSheetBuilder {

	/** Tall rows for the heading block, in points. Excel's default is 15. */
	private static final short TITLE_ROW_HEIGHT = 24;
	private static final short COMPANY_ROW_HEIGHT = 22;
	private static final short SPACER_ROW_HEIGHT = 6;

	private final Workbook workbook;
	private final ExcelStyles styles;

	public ExcelSheetBuilder(Workbook workbook, ExcelStyles styles) {
		this.workbook = workbook;
		this.styles = styles;
	}

	/**
	 * Writes the report to a new sheet named {@code sheetName}.
	 *
	 * @param sheetName worksheet tab name, max 31 chars and free of {@code : \ / ? * [ ]}
	 * @param report    the data to render
	 * @param company   company name shown in the document header
	 */
	public void build(String sheetName, ExcelReport report, String company) {
		Sheet sheet = workbook.createSheet(sheetName);
		List<ExcelColumn> columns = report.columns();
		int lastCol = columns.size() - 1;

		applyColumnWidths(sheet, columns);

		int rowIdx = 0;
		rowIdx = writeTitleBlock(sheet, report, company, lastCol, rowIdx);
		int headerRowIdx = rowIdx;
		writeHeader(sheet, columns, rowIdx++);

		int firstDataRow = rowIdx;
		int dataRowCount = 0;
		if (report.isEmpty()) {
			writeEmptyNotice(sheet, columns, rowIdx, firstDataRow);
			rowIdx++;
		} else {
			for (List<Object> data : report.rows()) {
				writeDataRow(sheet, columns, data, rowIdx++, dataRowCount % 2 == 1);
				dataRowCount++;
			}
		}
		int lastDataRow = rowIdx - 1;

		if (dataRowCount > 0) {
			writeTotalRow(sheet, columns, report.rows(), rowIdx++, lastCol);
		}

		writeFooter(sheet, rowIdx + 1, lastCol, dataRowCount);
		applySheetBehaviour(sheet, headerRowIdx, lastDataRow, lastCol);
	}

	// ---------------------------------------------------------------- blocks

	private int writeTitleBlock(Sheet sheet, ExcelReport report, String company, int lastCol, int rowIdx) {
		Row companyRow = sheet.createRow(rowIdx);
		companyRow.setHeightInPoints(COMPANY_ROW_HEIGHT);
		mergedCell(sheet, companyRow, 0, lastCol, company, styles.company());
		rowIdx++;

		Row titleRow = sheet.createRow(rowIdx);
		titleRow.setHeightInPoints(TITLE_ROW_HEIGHT);
		mergedCell(sheet, titleRow, 0, lastCol, report.title().toUpperCase(), styles.title());
		rowIdx++;

		Row metaRow = sheet.createRow(rowIdx);
		mergedCell(sheet, metaRow, 0, lastCol, report.subtitle(), styles.meta());
		rowIdx++;

		Row spacer = sheet.createRow(rowIdx);
		spacer.setHeightInPoints(SPACER_ROW_HEIGHT);
		return rowIdx + 1;
	}

	private void writeHeader(Sheet sheet, List<ExcelColumn> columns, int rowIdx) {
		Row headerRow = sheet.createRow(rowIdx);
		headerRow.setHeightInPoints(30);
		for (int i = 0; i < columns.size(); i++) {
			Cell cell = headerRow.createCell(i);
			cell.setCellValue(columns.get(i).header());
			cell.setCellStyle(styles.header());
		}
	}

	private void writeDataRow(Sheet sheet, List<ExcelColumn> columns, List<Object> data, int rowIdx, boolean zebra) {
		Row row = sheet.createRow(rowIdx);
		for (int i = 0; i < columns.size(); i++) {
			ExcelColumn column = columns.get(i);
			Object value = i < data.size() ? data.get(i) : null;
			Cell cell = row.createCell(i);
			cell.setCellStyle(styles.body(column.type(), zebra, value));
			writeValue(cell, column.type(), value);
		}
	}

	/**
	 * Writes {@code null} for a missing value rather than a placeholder. Writing {@code 0}
	 * or {@code "-"} for unknown data would fabricate a value that reads as real in a
	 * spreadsheet and feeds wrong numbers into any pivot or SUM the recipient builds.
	 */
	private void writeValue(Cell cell, ExcelColumn.Type type, Object value) {
		if (value == null) {
			cell.setBlank();
			return;
		}
		switch (type) {
			case TEXT, STATUS -> cell.setCellValue(value.toString());
			case INTEGER -> cell.setCellValue(asDouble(value));
			case DECIMAL, CURRENCY -> cell.setCellValue(asDouble(value));
			case DATE -> setDate(cell, value);
			case DATETIME -> setDateTime(cell, value);
		}
	}

	private void setDate(Cell cell, Object value) {
		if (value instanceof LocalDate date) {
			cell.setCellValue(date);
		} else if (value instanceof LocalDateTime dt) {
			cell.setCellValue(dt.toLocalDate());
		} else if (value instanceof ZonedDateTime zdt) {
			cell.setCellValue(zdt.toLocalDate());
		} else {
			cell.setCellValue(value.toString());
		}
	}

	private void setDateTime(Cell cell, Object value) {
		if (value instanceof LocalDateTime dt) {
			cell.setCellValue(dt);
		} else if (value instanceof ZonedDateTime zdt) {
			cell.setCellValue(zdt.toLocalDateTime());
		} else if (value instanceof LocalDate date) {
			cell.setCellValue(date.atStartOfDay());
		} else {
			cell.setCellValue(value.toString());
		}
	}

	private static double asDouble(Object value) {
		return value instanceof Number n ? n.doubleValue() : Double.parseDouble(value.toString());
	}

	private void writeEmptyNotice(Sheet sheet, List<ExcelColumn> columns, int rowIdx, int firstDataRow) {
		Row row = sheet.createRow(rowIdx);
		mergedCell(sheet, row, 0, columns.size() - 1, "Tidak ada data untuk periode ini.",
				styles.body(ExcelColumn.Type.TEXT, false, null));
	}

	/**
	 * Writes a grand-total row. Only numeric columns get a value; the label sits in the
	 * last non-numeric column before the first <em>totalled</em> column so it reads as a
	 * table footer rather than a floating cell.
	 *
	 * <p>"No." is an INTEGER column but must never be summed — it is a row counter, not a
	 * measure. It is therefore excluded from the anchor search by looking for the first
	 * numeric column past the row-numbering column.
	 */
	private void writeTotalRow(Sheet sheet, List<ExcelColumn> columns, List<List<Object>> rows, int rowIdx,
			int lastCol) {
		Row row = sheet.createRow(rowIdx);
		int firstTotalled = firstTotalledColumn(columns);
		if (firstTotalled < 0) {
			return;
		}
		int labelCol = Math.max(0, firstTotalled - 1);
		Cell label = row.createCell(labelCol);
		label.setCellValue("TOTAL");
		label.setCellStyle(styles.totalLabel());
		for (int i = 0; i < labelCol; i++) {
			row.createCell(i).setCellStyle(styles.totalLabel());
		}
		for (int i = labelCol + 1; i <= lastCol; i++) {
			Cell cell = row.createCell(i);
			ExcelColumn column = columns.get(i);
			if (isTotalled(column, i)) {
				cell.setCellValue(sum(rows, i));
				cell.setCellStyle(styles.totalFor(column));
			} else {
				cell.setCellStyle(styles.totalLabel());
			}
		}
	}

	/**
	 * Index of the first column that carries a sum, or {@code -1} when the report has none.
	 * A leading INTEGER column is treated as a row counter and skipped.
	 */
	private static int firstTotalledColumn(List<ExcelColumn> columns) {
		for (int i = 0; i < columns.size(); i++) {
			if (isTotalled(columns.get(i), i)) {
				return i;
			}
		}
		return -1;
	}

	/** True when this column participates in the total: numeric and not the row counter. */
	private static boolean isTotalled(ExcelColumn column, int index) {
		if (!column.isNumeric()) {
			return false;
		}
		// A numeric first column in a report that also has line numbering is the counter.
		return !(index == 0 && ExcelColumn.Type.INTEGER == column.type());
	}

	private static double sum(List<List<Object>> rows, int columnIndex) {
		double total = 0;
		for (List<Object> row : rows) {
			if (columnIndex >= row.size()) {
				continue;
			}
			Object value = row.get(columnIndex);
			if (value instanceof Number n) {
				total += n.doubleValue();
			}
		}
		return total;
	}

	private void writeFooter(Sheet sheet, int rowIdx, int lastCol, int dataRowCount) {
		Row row = sheet.createRow(rowIdx);
		String stamp = "Generated by CORE ERP on " + LocalDate.now() + "  \u00b7  "
				+ dataRowCount + " record(s)";
		mergedCell(sheet, row, 0, lastCol, stamp, styles.footer());
	}

	private static void applyColumnWidths(Sheet sheet, List<ExcelColumn> columns) {
		for (int i = 0; i < columns.size(); i++) {
			sheet.setColumnWidth(i, columns.get(i).width() * 256);
		}
	}

	private static void applySheetBehaviour(Sheet sheet, int headerRowIdx, int lastDataRow, int lastCol) {
		sheet.createFreezePane(0, headerRowIdx + 1);
		if (lastDataRow >= headerRowIdx) {
			sheet.setAutoFilter(new CellRangeAddress(headerRowIdx, lastDataRow, 0, lastCol));
		}
		sheet.setRepeatingRows(new CellRangeAddress(headerRowIdx, headerRowIdx, 0, lastCol));
		sheet.setFitToPage(true);
		sheet.setAutobreaks(true);
		var printSetup = sheet.getPrintSetup();
		printSetup.setLandscape(true);
		printSetup.setFitWidth((short) 1);
		printSetup.setFitHeight((short) 0);
		sheet.setMargin(PageMargin.HEADER, 0.4);
		sheet.setMargin(PageMargin.FOOTER, 0.4);
		sheet.getFooter().setCenter("Page &P of &N");
	}

	private static void mergedCell(Sheet sheet, Row row, int firstCol, int lastCol, String value, CellStyle style) {
		if (firstCol != lastCol) {
			sheet.addMergedRegion(new CellRangeAddress(row.getRowNum(), row.getRowNum(), firstCol, lastCol));
		}
		Cell cell = row.createCell(firstCol);
		cell.setCellValue(value == null ? "" : value);
		cell.setCellStyle(style);
		for (int i = firstCol + 1; i <= lastCol; i++) {
			row.createCell(i).setCellStyle(style);
		}
	}
}
